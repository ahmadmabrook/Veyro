def get_event(pool: Pool, tenant_id: str, *, event_id: str) -> dict[str, Any]:
    """One event's envelope and its delivery state. **Without the payload.**

    `events.event.read` would otherwise be a lateral read path around every other module's read
    permission: an independent reviewer held that one routine permission, was refused 403 by
    `/privacy/consent/history` and `/privacy/requests`, and read the same facts -- who consented
    to what, who filed which data subject request -- out of `evt_outbox.payload`. The event plane
    routes and traces; it is not a second way to read the data the owning module guards.

    A consumer still gets the payload, through `_event` on the delivery path, because that is
    what a handler is for. If a read route ever needs one, it has to ask the owning module's own
    read permission for it -- `catalog.owner_module` and `catalog.classification` are there to
    make that decidable.
    """
    event = _event(pool, tenant_id, event_id=event_id)
    event.pop("payload", None)
    with tenant_scope(pool, tenant_id) as conn:
        deliveries = conn.execute(
            "SELECT consumer, status, attempts, first_queued_at, handled_at, last_error"
            " FROM plt01.evt_deliveries WHERE event_id = %s ORDER BY consumer",
            (event_id,),
        ).fetchall()
    event["deliveries"] = [
        {"consumer": d[0], "status": d[1], "attempts": int(d[2]),
         "first_queued_at": d[3].isoformat(),
         "handled_at": d[4].isoformat() if d[4] else None, "last_error": d[5]}
        for d in deliveries
    ]
    return event


def trace(pool: Pool, tenant_id: str, *, correlation_id: str) -> list[dict[str, Any]]:
    """Everything that happened under one correlation id, in order.

    TSD paragraph 3241's operational explorer. One query, because the point of a correlation id
    is that it answers "what did this request cause" without anybody joining five tables by hand.
    """
    with tenant_scope(pool, tenant_id) as conn:
        rows = conn.execute(
            "SELECT event_id, event_type, schema_version, aggregate_type, aggregate_id,"
            " causation_id, occurred_at, status FROM plt01.evt_outbox"
            " WHERE correlation_id = %s ORDER BY occurred_at, event_id",
            (correlation_id,),
        ).fetchall()
    return [{"event_id": str(r[0]), "event_type": r[1], "schema_version": int(r[2]),
             "aggregate_type": r[3], "aggregate_id": str(r[4]),
             "causation_id": str(r[5]) if r[5] else None,
             "occurred_at": r[6].isoformat(), "status": r[7]} for r in rows]


def aggregate_history(
    pool: Pool, tenant_id: str, *, aggregate_type: str, aggregate_id: str
) -> list[dict[str, Any]]:
    """The timeline of one thing (TSD paragraph 3233: "operational timeline"), without
    payloads. See `get_event`."""
    with tenant_scope(pool, tenant_id) as conn:
        rows = conn.execute(
            "SELECT event_id, event_type, schema_version, aggregate_version, actor_id,"
            " correlation_id, occurred_at FROM plt01.evt_outbox"
            " WHERE aggregate_type = %s AND aggregate_id = %s ORDER BY occurred_at, event_id",
            (aggregate_type, aggregate_id),
        ).fetchall()
    # No payload, for the reason in `get_event`. The timeline says what happened to a thing and
    # when; what each event carried is the owning module's to disclose.
    return [{"event_id": str(r[0]), "event_type": r[1], "schema_version": int(r[2]),
             "aggregate_version": int(r[3]) if r[3] is not None else None,
             "actor_id": str(r[4]) if r[4] else None, "correlation_id": str(r[5]),
             "occurred_at": r[6].isoformat()} for r in rows]


def outbox_health(pool: Pool, tenant_id: str) -> dict[str, Any]:
    """What a relay operator needs in one read: backlog, oldest pending, dead letters.

    TSD paragraph 464 has REL-01 calling DAT-01 for event health during an incident. This is
    that read, and it is deliberately cheap: three aggregates over indexed predicates, so asking
    during an incident does not make the incident worse.
    """
    with tenant_scope(pool, tenant_id) as conn:
        pending = conn.execute(
            "SELECT count(*), min(occurred_at) FROM plt01.evt_outbox WHERE status = 'pending'"
        ).fetchone()
        undelivered = conn.execute(
            "SELECT count(*), min(first_queued_at) FROM plt01.evt_deliveries"
            " WHERE status = 'pending'"
        ).fetchone()
        quarantined = conn.execute(
            "SELECT count(*) FROM plt01.evt_dead_letters WHERE released_at IS NULL"
        ).fetchone()
    assert pending is not None and undelivered is not None and quarantined is not None
    return {
        "pending_events": int(pending[0]),
        "oldest_pending_at": pending[1].isoformat() if pending[1] else None,
        "pending_deliveries": int(undelivered[0]),
        "oldest_undelivered_at": undelivered[1].isoformat() if undelivered[1] else None,
        "dead_letters": int(quarantined[0]),
    }


# ------------------------------------------------------------------------------- internals

def _event(pool: Pool, tenant_id: str, *, event_id: str) -> dict[str, Any]:
    with tenant_scope(pool, tenant_id) as conn:
        row = conn.execute(
            "SELECT event_id, event_type, schema_version, aggregate_type, aggregate_id,"
            " aggregate_version, actor_id, correlation_id, causation_id, occurred_at, payload,"
            " idempotency_key, status FROM plt01.evt_outbox WHERE event_id = %s",
            (event_id,),
        ).fetchone()
    if row is None:
        raise NotFound("event_not_found")
    return {"event_id": str(row[0]), "event_type": row[1], "schema_version": int(row[2]),
            "aggregate_type": row[3], "aggregate_id": str(row[4]),
            "aggregate_version": int(row[5]) if row[5] is not None else None,
            "actor_id": str(row[6]) if row[6] else None, "correlation_id": str(row[7]),
            "causation_id": str(row[8]) if row[8] else None,
            "occurred_at": row[9].isoformat(), "payload": row[10],
            "idempotency_key": row[11], "status": row[12]}


def _check_name(error: errors.CheckViolation) -> str:
    """The constraint name, which is a fixed identifier in a migration this repository owns.

    Never the database's message, which can carry the offending value and would put request
    input into an error code that reaches the client.
    """
    name = getattr(error.diag, "constraint_name", None)
    return name or "check_violation"


