"""MOD-010 DAT-01 service: the outbox, the relay, delivery with retry, dead letters and replay.

The decisions live in `app.events.catalog` and `app.events.dispatch`. This module reads rows,
calls those, and writes what they return.

**`append_event` takes a connection, not a pool, and that is the whole module.** TSD paragraph
105 requires state and outbox to commit atomically; the only way to mean it is for the append to
run inside the caller's transaction, on the caller's connection, under the caller's tenant
context. Every other service in this repository takes a pool and opens its own `tenant_scope`,
and a version of this one that did the same would read identically while guaranteeing nothing:
the state change would commit and the event would be a separate transaction that could fail on
its own, or the event would commit and the state roll back and a consumer would act on something
that never happened. If you are tempted to add a pool-taking convenience wrapper, that wrapper is
the bug.

**Dispatch is a separate pass and may run as often as it likes.** Appending is synchronous with
the business change; delivering is not, and nothing in the request path waits for a consumer.
`dispatch_pending` claims with `FOR UPDATE SKIP LOCKED` so two relays can run at once without
either blocking or double-claiming.

**What is not here, and why.** TSD paragraph 271 names EventBridge, SNS, per-consumer SQS and an
S3 archive. None of them exists in this repository and none is simulated: a module that wrote
"published to SNS" into a row while sending nothing would be the fabricated-evidence shape this
codebase has already been bitten by. What is here is the half that has to be correct whatever
the transport turns out to be -- the atomic append, the per-consumer delivery state, the
deduplication, the retry budget, the quarantine and the replay policy -- and a `Handler`
protocol the transport will implement. The gap is recorded in CLAUDE.md.
"""

from __future__ import annotations

from datetime import datetime, timedelta
from time import monotonic
from typing import Any, Protocol

from psycopg import Connection, errors
from psycopg.types.json import Jsonb

from app.db import Pool, tenant_scope
from app.errors import Conflict, InvalidRequest, NotFound
from app.events import catalog, dispatch
from app.observability import metrics as obs


#: What a consumer is, from this module's point of view. The transport implements it; the tests
#: implement it; nothing here knows whether the other end is a queue, an HTTP call or a function.
class Handler(Protocol):
    def __call__(self, event: dict[str, Any]) -> None: ...


Registry = dict[str, Handler]


#: How long a claimed delivery is reserved while its handler runs. This is a lease, not a
#: backoff: the handler is called outside the claiming transaction, so without a reservation a
#: second relay could take the row while the first is still in the handler, settle it, and then
#: be overwritten by the first one's late success. The first backoff is two seconds, which is
#: shorter than plenty of honest handlers. `_record_failure` overwrites it with the real backoff
#: when a handler fails, so this only governs the in-flight window and the case where a relay
#: dies holding a delivery.
_CLAIM_LEASE = timedelta(minutes=1)


# ------------------------------------------------------------------------------ the outbox

def append_event(
    conn: Connection[Any], tenant_id: str, *, event_type: str, aggregate_type: str,
    aggregate_id: str, payload: dict[str, Any], correlation_id: str,
    actor_id: str | None = None, causation_id: str | None = None,
    aggregate_version: int | None = None, idempotency_key: str | None = None,
    schema_version: int | None = None, occurred_at: datetime | None = None,
) -> str:
    """AppendOutboxEvent, on the caller's connection and inside the caller's transaction.

    Returns the `event_id`. The id is generated by the database and **cannot be supplied**: it
    is globally unique across tenants, so a caller able to choose it could probe for another
    tenant's events by watching which values collide. A producer that needs its own handle
    passes `idempotency_key`, which is unique within the tenant and refuses a duplicate.

    The payload is validated against the catalogue before it is written -- exactly the declared
    fields, no more and no less -- so an event carrying something nobody approved fails at the
    producer rather than in a consumer, an archive and every later replay.
    """
    event = (catalog.require_event(event_type, schema_version)
             if schema_version is not None else catalog.latest(event_type))
    catalog.validate_payload(event.name, event.version, payload)
    if idempotency_key is not None and not idempotency_key.strip():
        raise InvalidRequest("idempotency_key_cannot_be_blank")
    try:
        row = conn.execute(
            """
            INSERT INTO plt01.evt_outbox
                (tenant_id, event_type, schema_version, aggregate_type, aggregate_id,
                 aggregate_version, actor_id, correlation_id, causation_id, occurred_at,
                 payload, idempotency_key)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, coalesce(%s, now()), %s, %s)
            RETURNING event_id
            """,
            (tenant_id, event.name, event.version, aggregate_type, aggregate_id,
             aggregate_version, actor_id, correlation_id, causation_id, occurred_at,
             Jsonb(payload), idempotency_key),
        ).fetchone()
    except errors.UniqueViolation:
        # The producer has already appended this event in this tenant. Raising rather than
        # returning the existing id is deliberate: the caller is inside a transaction that is
        # about to commit a state change, and a silent no-op here would commit the change
        # without an event. A command that means to be idempotent checks before it acts.
        raise Conflict("event_already_appended_for_this_idempotency_key") from None
    except errors.CheckViolation as e:
        raise InvalidRequest(_check_name(e)) from None
    assert row is not None
    return str(row[0])


# ------------------------------------------------------------------------------ subscriptions

def subscribe(
    pool: Pool, tenant_id: str, *, consumer: str, event_type: str, actor_id: str,
    correlation_id: str, replay_safety: str = "suppress", max_attempts: int = 5,
) -> dict[str, Any]:
    """Route an event type to a consumer, with that consumer's replay-safety declaration.

    `replay_safety` defaults to the strictest value rather than the convenient one: a consumer
    whose author did not think about replay is a consumer that is not safe for it.
    """
    if replay_safety not in dispatch.REPLAY_SAFETY:
        raise InvalidRequest("unknown_replay_safety")
    catalog.latest(event_type)  # refuses an event type this build does not define
    with tenant_scope(pool, tenant_id) as conn:
        # A deactivated subscription is reactivated rather than refused. The unique key spans
        # active and inactive rows, so an INSERT-only version answered
        # `consumer_already_subscribed_to_this_event_type` for a consumer that was not
        # subscribed at all -- an error saying the opposite of what was true, and a consumer
        # deactivated by mistake was permanently unroutable. The deactivation stamp is cleared
        # with it, because `evt_subscriptions_active_consistent` requires the two to agree.
        reactivated = conn.execute(
            "UPDATE plt01.evt_subscriptions"
            " SET active = true, deactivated_at = NULL, deactivated_by = NULL,"
            "     deactivate_correlation_id = NULL, replay_safety = %s, max_attempts = %s"
            " WHERE consumer = %s AND event_type = %s AND NOT active"
            " RETURNING subscription_id, registered_at",
            (replay_safety, max_attempts, consumer, event_type),
        ).fetchone()
        if reactivated is not None:
            return {"subscription_id": str(reactivated[0]), "consumer": consumer,
                    "event_type": event_type, "replay_safety": replay_safety,
                    "max_attempts": max_attempts,
                    "registered_at": reactivated[1].isoformat(), "reactivated": True}
        try:
            row = conn.execute(
                """
                INSERT INTO plt01.evt_subscriptions
                    (tenant_id, consumer, event_type, replay_safety, max_attempts,
                     registered_by, correlation_id)
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING subscription_id, registered_at
                """,
                (tenant_id, consumer, event_type, replay_safety, max_attempts, actor_id,
                 correlation_id),
            ).fetchone()
        except errors.UniqueViolation:
            raise Conflict("consumer_already_subscribed_to_this_event_type") from None
        except errors.CheckViolation as e:
            raise InvalidRequest(_check_name(e)) from None
    assert row is not None
    return {"subscription_id": str(row[0]), "consumer": consumer, "event_type": event_type,
            "replay_safety": replay_safety, "max_attempts": max_attempts,
            "registered_at": row[1].isoformat(), "reactivated": False}


def unsubscribe(
    pool: Pool, tenant_id: str, *, subscription_id: str, actor_id: str, correlation_id: str
) -> dict[str, Any]:
    """Deactivate a subscription. Never deletes it: a consumer that simply vanished is a
    consumer somebody will ask about when an old event turns up undelivered."""
    with tenant_scope(pool, tenant_id) as conn:
        row = conn.execute(
            "UPDATE plt01.evt_subscriptions SET active = false, deactivated_at = now(),"
            " deactivated_by = %s, deactivate_correlation_id = %s"
            " WHERE subscription_id = %s AND active"
            " RETURNING subscription_id, consumer, deactivated_at",
            (actor_id, correlation_id, subscription_id),
        ).fetchone()
    if row is None:
        raise NotFound("subscription_not_found_or_already_inactive")
    return {"subscription_id": str(row[0]), "consumer": row[1],
            "deactivated_at": row[2].isoformat()}


def list_subscriptions(
    pool: Pool, tenant_id: str, *, include_inactive: bool = False
) -> list[dict[str, Any]]:
    with tenant_scope(pool, tenant_id) as conn:
        rows = conn.execute(
            "SELECT subscription_id, consumer, event_type, replay_safety, max_attempts,"
            " active, registered_at, deactivated_at FROM plt01.evt_subscriptions"
            " WHERE (%s OR active) ORDER BY consumer, event_type",
            (include_inactive,),
        ).fetchall()
    return [{"subscription_id": str(r[0]), "consumer": r[1], "event_type": r[2],
             "replay_safety": r[3], "max_attempts": int(r[4]), "active": r[5],
             "registered_at": r[6].isoformat(),
             "deactivated_at": r[7].isoformat() if r[7] else None} for r in rows]


# ------------------------------------------------------------------------------ the relay

def dispatch_pending(pool: Pool, tenant_id: str, *, limit: int = 100) -> dict[str, Any]:
    """Fan pending outbox events out to their subscribers, creating one delivery row each.

    This is the half of publication that does not need a transport: whatever the transport turns
    out to be, every subscriber needs a row saying the event is theirs to handle, with its own
    attempt count. Claiming uses `FOR UPDATE SKIP LOCKED` so two relays running at once each
    take a different slice instead of blocking or double-claiming.

    An event with no active subscriber is still marked dispatched. The alternative -- leaving it
    pending for ever in case somebody subscribes later -- means the pending set grows without
    bound and the claim index stops being selective. The event is still in the outbox and a
    replay can reach it, which is the right tool for a consumer that arrived late.
    """
    fanned = 0
    created = 0
    with tenant_scope(pool, tenant_id) as conn:
        claimed = conn.execute(
            "SELECT event_id, event_type FROM plt01.evt_outbox"
            " WHERE status = 'pending' AND available_at <= now()"
            " ORDER BY occurred_at LIMIT %s FOR UPDATE SKIP LOCKED",
            (limit,),
        ).fetchall()
        for event_id, event_type in claimed:
            consumers = conn.execute(
                "SELECT consumer FROM plt01.evt_subscriptions"
                " WHERE event_type = %s AND active",
                (event_type,),
            ).fetchall()
            for (consumer,) in consumers:
                # ON CONFLICT DO NOTHING rather than a prior SELECT: the delivery row may
                # already exist because a replay created it, and the primary key is the
                # deduplication. Letting the database answer avoids a check-then-act window.
                # The conflict target is named rather than left bare: `ON CONFLICT DO
                # NOTHING` with no target stays valid SQL if the primary key is ever dropped and
                # simply stops deduplicating, so at-least-once would silently become
                # at-least-twice. Naming it makes that a loud error. Found by review.
                result = conn.execute(
                    "INSERT INTO plt01.evt_deliveries (tenant_id, consumer, event_id)"
                    " VALUES (%s, %s, %s)"
                    " ON CONFLICT (tenant_id, consumer, event_id) DO NOTHING",
                    (tenant_id, consumer, event_id),
                )
                created += result.rowcount
            conn.execute(
                "UPDATE plt01.evt_outbox SET status = 'dispatched', dispatched_at = now()"
                " WHERE event_id = %s",
                (event_id,),
            )
            fanned += 1
    return {"events_dispatched": fanned, "deliveries_created": created}


def deliver_pending(
    pool: Pool, tenant_id: str, *, consumer: str, handlers: Registry, limit: int = 100,
) -> dict[str, Any]:
    """Run one consumer's pending deliveries through its handler.

    **Each delivery is its own transaction.** One handler raising must not roll back the rows
    that already succeeded, and the attempt count of a failure has to survive the failure --
    which it cannot if it is written inside a transaction the exception rolls back. That is the
    `_settled` lesson from MOD-007 and MOD-008 in its original form: the evidence of a refusal
    cannot live in the transaction the refusal destroys.
    """
    handled = 0
    failed = 0
    dead = 0
    skipped = 0
    # Durations are accumulated across the batch and written once at the end rather than per
    # delivery. The metric store buckets by the hour, so a hundred deliveries in one pass would
    # otherwise be a hundred upserts contending on the same row for the same answer -- and the
    # (observations, total) shape exists precisely so a batch can be one point.
    attempted = 0
    succeeded = 0
    duration_ms_total = 0.0
    handler = handlers.get(consumer)
    if handler is None:
        raise InvalidRequest("no_handler_registered_for_this_consumer")

    for event_id, claimed_attempts in _claim_deliveries(pool, tenant_id, consumer=consumer,
                                                        limit=limit):
        event = _event(pool, tenant_id, event_id=event_id)
        attempted += 1
        started = monotonic()
        try:
            handler(event)
        except Exception as e:  # noqa: BLE001 -- recorded against this delivery, then on to the next
            duration_ms_total += (monotonic() - started) * 1000
            verdict = _record_failure(pool, tenant_id, consumer=consumer, event_id=event_id,
                                      error=f"{type(e).__name__}: {e}"[:500])
            if verdict == "dead":
                dead += 1
            elif verdict == "gone":
                skipped += 1
            else:
                failed += 1
            continue
        duration_ms_total += (monotonic() - started) * 1000
        succeeded += 1
        with tenant_scope(pool, tenant_id) as conn:
            # `AND status = 'pending'` and an explicit attempt count, not `attempts + 1`.
            # The claim is a lease rather than a lock, so a handler slower than its lease can
            # have its row settled by another relay; without the guard this late success
            # overwrote that settlement, and the blind increment pushed the row past the
            # subscription's attempt budget. Found by independent review.
            settled = conn.execute(
                "UPDATE plt01.evt_deliveries SET status = 'handled', handled_at = now(),"
                " attempts = %s, last_error = NULL"
                " WHERE consumer = %s AND event_id = %s AND status = 'pending'",
                (claimed_attempts + 1, consumer, event_id),
            )
            if settled.rowcount == 0:
                # Somebody else settled it while the handler ran. The handler did run, so this
                # is at-least-once behaving as documented; what must not happen is this call
                # rewriting a terminal row.
                skipped += 1
                continue
        handled += 1
    if attempted:
        # Recorded after the loop, in its own transaction, and **its failure is swallowed**.
        # The deliveries have already committed and the handlers have already run; losing these
        # two points is a gap in a chart, while letting the write propagate would discard the
        # summary the caller needs to know what the relay did. Narrow and deliberate, the same
        # argument `main.py`'s `_count_denial` makes: the work that happened outranks its own
        # bookkeeping.
        try:
            obs.observe(pool, tenant_id, metric_key="events.delivery_duration",
                        total=duration_ms_total, observations=attempted,
                        dimensions={"consumer": consumer})
            obs.observe(pool, tenant_id, metric_key="events.delivery_success",
                        total=float(succeeded), observations=attempted,
                        dimensions={"consumer": consumer})
        except Exception:  # noqa: BLE001 -- see above; the delivery summary is what must return
            pass
    return {"consumer": consumer, "handled": handled, "retrying": failed,
            "dead_lettered": dead, "skipped": skipped}


def _claim_deliveries(
    pool: Pool, tenant_id: str, *, consumer: str, limit: int
) -> list[tuple[str, int]]:
    """Take a slice of this consumer's due deliveries, leasing each, and return (id, attempts).

    The attempt count comes back with the id because the caller writes it explicitly on success
    rather than incrementing blind: `attempts + 1` in a statement racing another relay is how a
    delivery exceeds its own budget.

    The lease is `max(backoff, _CLAIM_LEASE)`. The backoff alone was the reservation, and the
    first one is two seconds -- shorter than plenty of honest handlers, so a slow handler's row
    became claimable while it was still running.
    """
    with tenant_scope(pool, tenant_id) as conn:
        rows = conn.execute(
            "SELECT event_id, attempts FROM plt01.evt_deliveries"
            " WHERE consumer = %s AND status = 'pending' AND available_at <= now()"
            " ORDER BY first_queued_at LIMIT %s FOR UPDATE SKIP LOCKED",
            (consumer, limit),
        ).fetchall()
        claimed = []
        for event_id, attempts in rows:
            lease = max(dispatch.backoff_seconds(int(attempts)), _CLAIM_LEASE)
            conn.execute(
                "UPDATE plt01.evt_deliveries SET available_at = now() + %s"
                " WHERE consumer = %s AND event_id = %s",
                (lease, consumer, event_id),
            )
            claimed.append((str(event_id), int(attempts)))
    return claimed


def _record_failure(
    pool: Pool, tenant_id: str, *, consumer: str, event_id: str, error: str
) -> str:
    """Count the failure, and quarantine when the budget is gone. Its own transaction.

    **This must not raise.** It is called from the relay's loop over a batch, and a raise here
    aborts the batch: every healthy delivery behind the failing one goes unhandled, and the
    failure itself is recorded nowhere -- no attempt counted, no error written, no quarantine --
    so the row is claimed again on the next pass and the consumer stops for ever. An earlier
    version raised `NotFound` when the delivery had no matching subscription, which turned one
    mis-scoped replay into a permanently stalled consumer with a growing backlog and zero dead
    letters, pointing an operator away from the cause. Found by independent review.

    Returns `pending`, `dead`, or `gone` when the delivery is no longer there to record against.
    """
    with tenant_scope(pool, tenant_id) as conn:
        delivery = conn.execute(
            "SELECT attempts FROM plt01.evt_deliveries"
            " WHERE consumer = %s AND event_id = %s AND status = 'pending'",
            (consumer, event_id),
        ).fetchone()
        if delivery is None:
            # Settled by another relay while the handler ran, or released from under us. There
            # is nothing to count the failure against and nothing is wrong with the system.
            return "gone"
        budget = conn.execute(
            "SELECT s.max_attempts FROM plt01.evt_subscriptions s"
            " WHERE s.consumer = %s AND s.event_type = ("
            "    SELECT event_type FROM plt01.evt_outbox WHERE event_id = %s) AND s.active",
            (consumer, event_id),
        ).fetchone()
        if budget is None:
            # A delivery with no active subscription behind it: the consumer was deactivated, or
            # the delivery was created by a replay for a type it does not subscribe to.
            # Quarantine it with that as the reason rather than retrying something nothing
            # routes -- visible, terminal, and releasable once somebody fixes the routing.
            row = (int(delivery[0]), 1)
        else:
            row = (int(delivery[0]), int(budget[0]))
        verdict = dispatch.after_failure(attempts=row[0], max_attempts=row[1], error=error)
        reason = error if budget is not None else f"no active subscription: {error}"
        if verdict.status == "dead":
            conn.execute(
                "UPDATE plt01.evt_deliveries SET status = 'dead', handled_at = now(),"
                " attempts = %s, last_error = %s"
                " WHERE consumer = %s AND event_id = %s AND status = 'pending'",
                (verdict.attempts, reason, consumer, event_id),
            )
            conn.execute(
                "INSERT INTO plt01.evt_dead_letters"
                "   (tenant_id, event_id, consumer, reason, attempts)"
                " VALUES (%s, %s, %s, %s, %s)"
                " ON CONFLICT (tenant_id, consumer, event_id) WHERE released_at IS NULL"
                " DO NOTHING",
                (tenant_id, event_id, consumer, reason, verdict.attempts),
            )
        else:
            conn.execute(
                "UPDATE plt01.evt_deliveries SET attempts = %s, available_at = now() + %s,"
                " last_error = %s"
                " WHERE consumer = %s AND event_id = %s AND status = 'pending'",
                (verdict.attempts, verdict.wait, reason, consumer, event_id),
            )
    return verdict.status


# ------------------------------------------------------------------------------ dead letters

def list_dead_letters(
    pool: Pool, tenant_id: str, *, include_released: bool = False
) -> list[dict[str, Any]]:
    with tenant_scope(pool, tenant_id) as conn:
        rows = conn.execute(
            "SELECT dead_letter_id, event_id, consumer, reason, attempts, quarantined_at,"
            " released_at, released_by, release_reason FROM plt01.evt_dead_letters"
            " WHERE (%s OR released_at IS NULL) ORDER BY quarantined_at DESC",
            (include_released,),
        ).fetchall()
    return [{"dead_letter_id": str(r[0]), "event_id": str(r[1]), "consumer": r[2],
             "reason": r[3], "attempts": int(r[4]), "quarantined_at": r[5].isoformat(),
             "released_at": r[6].isoformat() if r[6] else None,
             "released_by": str(r[7]) if r[7] else None,
             "release_reason": r[8]} for r in rows]


def release_dead_letter(
    pool: Pool, tenant_id: str, *, dead_letter_id: str, reason: str, actor_id: str,
    correlation_id: str,
) -> dict[str, Any]:
    """Requeue a quarantined delivery, attributed.

    Releasing is a decision to run a consumer against an event that already broke it, so the row
    records who decided and why. The delivery goes back to `pending` with its attempt count
    reset: the operator is asserting that whatever failed has been fixed, and a release that
    kept the exhausted count would dead-letter again on the first attempt.
    """
    if not reason.strip():
        raise InvalidRequest("release_reason_required")
    with tenant_scope(pool, tenant_id) as conn:
        row = conn.execute(
            "UPDATE plt01.evt_dead_letters SET released_at = now(), released_by = %s,"
            " release_reason = %s, release_correlation_id = %s"
            " WHERE dead_letter_id = %s AND released_at IS NULL"
            " RETURNING event_id, consumer",
            (actor_id, reason, correlation_id, dead_letter_id),
        ).fetchone()
        if row is None:
            raise NotFound("dead_letter_not_found_or_already_released")
        conn.execute(
            "UPDATE plt01.evt_deliveries SET status = 'pending', handled_at = NULL,"
            " attempts = 0, available_at = now(), last_error = NULL"
            " WHERE consumer = %s AND event_id = %s",
            (row[1], row[0]),
        )
    return {"dead_letter_id": dead_letter_id, "event_id": str(row[0]), "consumer": row[1],
            "released_by": actor_id, "requeued": True}


# ------------------------------------------------------------------------------ replay

def request_replay(
    pool: Pool, tenant_id: str, *, consumer: str, event_types: list[str],
    from_time: datetime, to_time: datetime, actor_id: str, correlation_id: str,
    side_effects: str = "suppress", side_effects_reason: str | None = None,
) -> dict[str, Any]:
    """Open a replay job. Its terms are fixed here and cannot move afterwards.

    Snapshotting the window, the type set and the side-effect policy at request time rather than
    reading them again when the job runs is the lesson from MOD-008's review: terms re-derived
    at decision time can be changed by whoever holds the write permission after the request was
    approved. A job whose scope could widen between approval and execution is an approval of
    something else.

    `side_effects` defaults to `suppress` and `allow` requires a written reason, per TSD
    paragraph 200.
    """
    if side_effects not in dispatch.SIDE_EFFECT_POLICIES:
        raise InvalidRequest("unknown_side_effect_policy")
    if side_effects == "allow" and not (side_effects_reason or "").strip():
        raise InvalidRequest("allowing_side_effects_on_a_replay_needs_a_reason")
    if not event_types:
        raise InvalidRequest("event_types_required")
    for name in event_types:
        catalog.latest(name)
    if to_time <= from_time:
        raise InvalidRequest("replay_window_must_be_positive")
    with tenant_scope(pool, tenant_id) as conn:
        try:
            row = conn.execute(
                """
                INSERT INTO plt01.evt_replay_jobs
                    (tenant_id, consumer, event_types, from_time, to_time, side_effects,
                     side_effects_reason, requested_by, correlation_id)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING job_id, requested_at
                """,
                (tenant_id, consumer, event_types, from_time, to_time, side_effects,
                 side_effects_reason, actor_id, correlation_id),
            ).fetchone()
        except errors.CheckViolation as e:
            raise InvalidRequest(_check_name(e)) from None
    assert row is not None
    return {"job_id": str(row[0]), "consumer": consumer, "event_types": event_types,
            "side_effects": side_effects, "status": "requested",
            "requested_at": row[1].isoformat()}


def run_replay(
    pool: Pool, tenant_id: str, *, job_id: str, actor_id: str, correlation_id: str
) -> dict[str, Any]:
    """Queue the job's events for its consumer, or record that they were suppressed.

    **Decided per event, from that event's own subscription.** The first version read one
    subscription for the whole job -- `... WHERE event_type = ANY(%s) ... LIMIT 1` -- and
    applied its `replay_safety` to every event in it. An independent review showed that fails
    in both directions, and which one you get depends on the query planner:

    * A consumer that is `safe` for one type and `suppress` for another had its `suppress`-class
      events delivered under the default policy, with no reason written and nobody overriding
      anything. TSD paragraph 200's default-suppress, defeated by listing a second event type.
    * With the rows in the other order the whole job suppressed, including the type the operator
      asked to rebuild -- and a `suppressed` delivery row is terminal, while every later insert
      is `ON CONFLICT DO NOTHING`, so **nothing in this module could undo it**.

    A type the consumer does not subscribe to is skipped entirely rather than queued. It used to
    be queued, which let a caller holding the replay permissions route any event type to any
    consumer name and bypass `evt_subscriptions` -- the table that is supposed to *be* the
    routing authority. A subscription lookup proves a subscription exists; it does not authorise
    these events.

    What this does not do is call the handler. A replayed event takes the same path as a live
    one through `deliver_pending`, including the deduplication, which is what stops a replay
    re-running a consumer that already handled the event.
    """
    with tenant_scope(pool, tenant_id) as conn:
        job = conn.execute(
            "SELECT consumer, event_types, from_time, to_time, side_effects, status"
            " FROM plt01.evt_replay_jobs WHERE job_id = %s FOR UPDATE",
            (job_id,),
        ).fetchone()
        if job is None:
            raise NotFound("replay_job_not_found")
        if job[5] != "requested":
            raise Conflict(f"replay_job_is_{job[5]}")
        consumer, event_types, from_time, to_time, side_effects = (
            job[0], list(job[1]), job[2], job[3], job[4])

        # The consumer's own declaration, per type. Types it does not subscribe to are absent
        # from this map and are skipped below.
        routed = {
            row[0]: row[1] for row in conn.execute(
                "SELECT event_type, replay_safety FROM plt01.evt_subscriptions"
                " WHERE consumer = %s AND event_type = ANY(%s) AND active",
                (consumer, event_types),
            ).fetchall()
        }
        if not routed:
            raise NotFound("consumer_has_no_active_subscription_to_these_event_types")

        conn.execute(
            # Attributed. `requested_by` says who asked; this says who pressed the button, and a
            # job carrying `side_effects = 'allow'` re-delivers a window of events with their
            # effects live. The same rule MOD-009 learned about releasing a legal hold.
            "UPDATE plt01.evt_replay_jobs SET status = 'running', started_at = now(),"
            " ran_by = %s, run_correlation_id = %s WHERE job_id = %s",
            (actor_id, correlation_id, job_id),
        )
        events = conn.execute(
            "SELECT event_id, event_type FROM plt01.evt_outbox"
            " WHERE event_type = ANY(%s) AND occurred_at >= %s AND occurred_at < %s"
            " ORDER BY occurred_at",
            (list(routed), from_time, to_time),
        ).fetchall()

        queued = 0
        suppressed = 0
        skipped = 0
        for event_id, event_type in events:
            safety = routed.get(event_type)
            if safety is None:
                skipped += 1
                continue
            action = dispatch.replay_action(replay_safety=safety, side_effects=side_effects)
            if action == "suppress":
                written = conn.execute(
                    "INSERT INTO plt01.evt_deliveries"
                    "   (tenant_id, consumer, event_id, status, handled_at, from_replay_job_id)"
                    " VALUES (%s, %s, %s, 'suppressed', now(), %s)"
                    " ON CONFLICT (tenant_id, consumer, event_id) DO NOTHING",
                    (tenant_id, consumer, event_id, job_id),
                )
                suppressed += written.rowcount
            else:
                # A delivery already handled stays handled: that is the deduplication, and it is
                # what makes a replay safe to run twice. `rowcount` rather than a blind
                # increment, so `events_replayed` counts rows actually created instead of rows
                # considered.
                written = conn.execute(
                    "INSERT INTO plt01.evt_deliveries"
                    "   (tenant_id, consumer, event_id, from_replay_job_id)"
                    " VALUES (%s, %s, %s, %s)"
                    " ON CONFLICT (tenant_id, consumer, event_id) DO NOTHING",
                    (tenant_id, consumer, event_id, job_id),
                )
                queued += written.rowcount
        conn.execute(
            "UPDATE plt01.evt_replay_jobs SET status = 'completed', finished_at = now(),"
            " events_replayed = %s WHERE job_id = %s",
            (queued + suppressed, job_id),
        )
    return {"job_id": job_id, "consumer": consumer, "status": "completed",
            # Per type, because one job can route two types to two different outcomes and a
            # single `action` would have to lie about one of them.
            "actions": {event_type: dispatch.replay_action(replay_safety=safety,
                                                           side_effects=side_effects)
                        for event_type, safety in sorted(routed.items())},
            "events_queued": queued, "events_suppressed": suppressed,
            "events_skipped": skipped,
            "events_replayed": queued + suppressed}


