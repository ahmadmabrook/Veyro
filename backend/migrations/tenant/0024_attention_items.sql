-- MOD-026 slice 4a (AUT-02-R07 and the three screens it draws): what the canvases need and
-- the slice-1 schema cannot express.
--
-- ADM-TSK-01, ADM-CC-06 and ADM-CC-07 are MOD-026's own surface, and the owner directive of
-- 2026-11-18 makes them part of the module rather than an afterthought -- so "when the
-- design requires missing backend functionality, implement it" makes this schema rather
-- than a deviation to note. ADR-0009's slice 4 was amended with the reasoning per item
-- before any of it was written, because reading the drawings found four things that the
-- line "the workload read the three screens draw" had understated.
--
-- Nothing here is a countdown: check 112 sweeps this prefix for a stored one, and the
-- snooze below is deliberately not a status for that reason among others.

-- ------------------------------------------------------- where the work came from
--
-- ADM-TSK-01: "Three sources: assigned by a person, generated by an automation, or
-- suggested by Veyro. The source is always named -- a task nobody can account for gets
-- ignored."
--
-- That second sentence is the whole specification. The set is closed for `subject_kind`'s
-- reason -- free text makes "how much of this queue is automation" a group-by over typos,
-- and it is the first thing a manager filters on -- and the column is NOT NULL because a
-- row that declines to say is the row the canvas says gets ignored.
--
-- **In no UPDATE grant.** Where work came from does not change. A granted column no service
-- writes is an unattributed edit path, which is MOD-016's `cat_prices.effective_to` and
-- MOD-019's rota times; here the edit would rewrite who is accountable for the row
-- existing at all.
ALTER TABLE plt01.tsk_tasks ADD COLUMN source text NOT NULL DEFAULT 'manual';
ALTER TABLE plt01.tsk_cases ADD COLUMN source text NOT NULL DEFAULT 'manual';
ALTER TABLE plt01.tsk_tasks ADD CONSTRAINT tsk_tasks_source
    CHECK (source IN ('manual', 'automation', 'ai'));
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_source
    CHECK (source IN ('manual', 'automation', 'ai'));
-- **The default backfills and then goes.** Every row written so far came from a person or a
-- test, so `manual` is true of all of them; leaving the default in place afterwards would
-- make "the source is always named" false for the first caller who forgets, which is the
-- state the column exists to prevent.
ALTER TABLE plt01.tsk_tasks ALTER COLUMN source DROP DEFAULT;
ALTER TABLE plt01.tsk_cases ALTER COLUMN source DROP DEFAULT;
-- The canvas's "Billing run · automatic" detail is the title's job. A free-text source
-- detail would be MOD-010's "the restricted-field rule checks names, and a value can carry
-- anything", plus one more residue column an erasure cannot reach.

-- ------------------------------------------------------- who owns an exception
--
-- ADM-CC-06's states are *unassigned*, *assigned to me*, *assigned to someone else* (every
-- action visible but read-only, with a "Take over that records the handover") and
-- *resolved*. A task has carried `assignee_person_id` since slice 1 and a case carried
-- none, so four of those five were unrepresentable on the record the sheet is about.
--
-- The handover *history* is a `tsk_case_entries` row rather than a second column pair, which
-- is why `assignment` joins the entry vocabulary below: "who has it now" is state and "who
-- handed it over and when" is what happened, and this module already keeps those apart.
ALTER TABLE plt01.tsk_cases ADD COLUMN assignee_person_id uuid;
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_assignee_fkey
    FOREIGN KEY (tenant_id, assignee_person_id)
    REFERENCES plt01.ppl_persons (tenant_id, person_id);

-- ------------------------------------------------------- a deferral, not a dismissal
--
-- ADM-CC-06: "Snoozing requires a reason and a return date -- an exception cannot be
-- dismissed, only deferred with an account of why."
--
-- **Not a status, which is the decision worth reading.** `tsk_case_resolution_is_final`
-- ranks open/resolved/closed and admits no going back; a snooze returns to the queue, so a
-- fourth status would need that rank function to admit a reversal -- and two encodings of
-- one rule that disagree is MOD-020's waitlist edge, where from the moment one member
-- failed to answer an offer nobody was promoted again while places sat free. A case is
-- *snoozed* when `status = 'open' AND snoozed_until > now()`: derived, which is this
-- module's own no-stored-countdown discipline and keeps the forward-only invariant intact.
ALTER TABLE plt01.tsk_cases ADD COLUMN snoozed_at timestamptz;
ALTER TABLE plt01.tsk_cases ADD COLUMN snoozed_until timestamptz;
ALTER TABLE plt01.tsk_cases ADD COLUMN snooze_reason text;
ALTER TABLE plt01.tsk_cases ADD COLUMN snoozed_by uuid;
ALTER TABLE plt01.tsk_cases ADD COLUMN snooze_correlation_id uuid;
-- All five or none. The reason is the canvas's "account of why", so a blank one is refused
-- by the same expression every other stated reason in this build uses -- `~ '[^[:space:]]'`
-- rather than `length(btrim(x)) > 0`, which a single tab satisfied across 118 constraints.
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_snooze_attributed CHECK (
    (snoozed_at IS NULL AND snoozed_until IS NULL AND snooze_reason IS NULL
     AND snoozed_by IS NULL AND snooze_correlation_id IS NULL)
    OR (snoozed_at IS NOT NULL AND snoozed_until IS NOT NULL
        AND coalesce(snooze_reason, '') ~ '[^[:space:]]'
        AND snoozed_by IS NOT NULL AND snooze_correlation_id IS NOT NULL));
-- **One-sided, and against a column the same statement writes.** `snoozed_until` measured
-- only against `snoozed_at` would be a bound between two values the same writer supplies,
-- which is not a bound: MOD-021 parked an unlock three days out and had it openable for
-- forty-five seconds on the night it chose. So `snoozed_at` is pinned to real time the way
-- `tsk_case_entries.occurred_at` is -- forward only, because late is legitimate and a lower
-- bound fails every existing row the next time the constraint is validated.
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_snooze_not_in_the_future
    CHECK (snoozed_at IS NULL OR snoozed_at <= now() + interval '5 minutes');
-- A year, because a deferral longer than that is somebody deciding not to deal with it, and
-- the canvas says an exception cannot be dismissed.
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_snooze_is_bounded CHECK (
    snoozed_until IS NULL
    OR (snoozed_until > snoozed_at AND snoozed_until <= snoozed_at + interval '1 year'));
-- A resolved case is not deferred: the two say opposite things about whether anybody still
-- has to look, and a row saying both is a row no queue read can place.
ALTER TABLE plt01.tsk_cases ADD CONSTRAINT tsk_cases_snooze_is_not_a_resolution
    CHECK (snoozed_until IS NULL OR status = 'open');

-- ------------------------------------------------------- the records an exception is about
--
-- ADM-CC-06: "6 payments failed overnight ... THE SIX RECORDS · EACH LINKS TO ITS MEMBER".
--
-- A case has exactly one subject, which is right for the ordinary case and cannot express an
-- exception that is *about* six members. The singular subject stays what the case is filed
-- under -- `tenant`, for a billing run -- and the six are rows here. This is the one of the
-- four that needs a table rather than a column, and the alternative considered was six
-- nullable id columns, which is MOD-021's supersession shape and silently switches off a
-- composite foreign key under MATCH SIMPLE.
CREATE TABLE plt01.tsk_case_affected (
    tenant_id uuid NOT NULL REFERENCES plt01_platform.tenants (tenant_id),
    case_id uuid NOT NULL,
    affected_kind text NOT NULL,
    affected_id uuid NOT NULL,
    added_at timestamptz NOT NULL DEFAULT now(),
    added_by uuid NOT NULL,
    correlation_id uuid NOT NULL,
    withdrawn_at timestamptz,
    withdrawn_by uuid,
    withdraw_reason text,
    withdraw_correlation_id uuid,
    -- **The subject is in the key**, so "6 affected" is a count nobody can inflate by
    -- adding the same member twice -- and that figure is what the sheet's header states and
    -- what a batch action is sized by.
    PRIMARY KEY (tenant_id, case_id, affected_kind, affected_id),
    FOREIGN KEY (tenant_id, case_id) REFERENCES plt01.tsk_cases (tenant_id, case_id),
    -- The subject vocabulary minus `tenant`: an affected record is a specific thing, and a
    -- case about the tenant is about the row's own `tenant_id`, which RLS already bounds.
    -- There is no foreign key for the same reason `tsk_tasks.subject_id` has none -- see
    -- `app/tasks/subjects.py`, which says per kind whether the service resolves it or
    -- records it as a claim.
    CONSTRAINT tsk_case_affected_kind CHECK (affected_kind IN (
        'member', 'lead', 'invoice', 'incident', 'device', 'booking', 'asset', 'workflow')),
    -- **A withdrawal, not a delete.** Adding one is routine `tasks.case.write`, and a
    -- routine permission whose every act is uncorrectable is MOD-013's rule from the other
    -- side -- the shape that made ADM-SCH-04's rota form unbuildable until `0017`. "Was
    -- this member ever on this exception, and who said so" is asked precisely when somebody
    -- was contacted by mistake.
    CONSTRAINT tsk_case_affected_withdrawal_attributed CHECK (
        (withdrawn_at IS NULL AND withdrawn_by IS NULL AND withdraw_reason IS NULL
         AND withdraw_correlation_id IS NULL)
        OR (withdrawn_at IS NOT NULL AND withdrawn_by IS NOT NULL
            AND coalesce(withdraw_reason, '') ~ '[^[:space:]]'
            AND withdraw_correlation_id IS NOT NULL))
);
ALTER TABLE plt01.tsk_case_affected ENABLE ROW LEVEL SECURITY;
ALTER TABLE plt01.tsk_case_affected FORCE ROW LEVEL SECURITY;
CREATE POLICY tsk_case_affected_tenant ON plt01.tsk_case_affected
    USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
    WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
-- "Every exception this member is on" is the sheet's own "Open ↗" read in reverse, and it is
-- what a Member 360 section would ask for.
CREATE INDEX tsk_case_affected_by_subject
    ON plt01.tsk_case_affected (tenant_id, affected_kind, affected_id);

GRANT SELECT, INSERT ON plt01.tsk_case_affected TO veyro_cp_app, veyro_cp_worker;
-- The withdrawal only. Not `affected_kind`, `affected_id`, `added_by` or `added_at`: which
-- record this is and who put it here is what the row exists to state.
GRANT UPDATE (withdrawn_at, withdrawn_by, withdraw_reason, withdraw_correlation_id)
    ON plt01.tsk_case_affected TO veyro_cp_app, veyro_cp_worker;

-- ------------------------------------------------------- two more entry kinds
--
-- A handover and a deferral are neither a note nor a status change, and the canvas makes
-- both first-class acts with their own accounts. A widening, so it invalidates no existing
-- row -- but it changes the constraint text, so check 112's pin and the sweep both run
-- again, which is this file's own "a schema change means re-running the sweep".
ALTER TABLE plt01.tsk_case_entries DROP CONSTRAINT tsk_case_entries_kind;
ALTER TABLE plt01.tsk_case_entries ADD CONSTRAINT tsk_case_entries_kind CHECK (
    entry_kind IN ('note', 'communication', 'document', 'status_change', 'escalation',
                   'assignment', 'deferral'));

-- ------------------------------------------------------- the case UPDATE grant
--
-- The assignee and the snooze five join it; `source` deliberately does not.
REVOKE UPDATE ON plt01.tsk_cases FROM veyro_cp_app, veyro_cp_worker;
GRANT UPDATE (title, queue_id, priority, status, resolved_at, resolved_by,
              resolution_reason, resolve_correlation_id, assignee_person_id,
              snoozed_at, snoozed_until, snooze_reason, snoozed_by,
              snooze_correlation_id)
    ON plt01.tsk_cases TO veyro_cp_app, veyro_cp_worker;

-- ------------------------------------------------------- a carried-over hardening
--
-- `tsk_sla_clocks.started_at` has been unbounded since `0021`. `start_clock` writes `now()`
-- in SQL, the UPDATE grant excludes the column and `tsk_sla_settlement_is_final` freezes
-- it, so nothing reachable moves it -- and MOD-011's unbounded `observed_at`, which let a
-- routine caller hold an objective green through an outage still to come, is the precedent
-- for closing it anyway. A clock started in the future never breaches.
--
-- Anchored to `created_at` rather than to `now()`, because the row carries one and both are
-- written by the same statement: a row-local bound needs no re-validation argument at all,
-- which is the better shape where it is available.
ALTER TABLE plt01.tsk_sla_clocks ADD CONSTRAINT tsk_sla_clocks_start_not_in_the_future
    CHECK (started_at <= created_at + interval '5 minutes');
