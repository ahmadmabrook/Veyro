#!/usr/bin/env node
/**
 * Generate the CSS custom properties and the token module from `ds.json`.
 *
 * **Generated, because a hand-written copy of a token table drifts from it.** The design
 * system is the authority; this writes the two artefacts a browser and a component need, and
 * `--check` regenerates into memory and diffs so a hand-edit fails CI rather than surviving.
 * That is the same cost MOD-019's definition pin accepts deliberately: a legitimate change
 * fails until it is regenerated, which is the moment a human reads the diff.
 *
 * Two outputs:
 *   tokens.generated.css -- `:root` light, `[data-theme="dark"]` dark, and the type scale.
 *   tokens.generated.mjs -- the same values for code that needs them outside CSS.
 *
 * Layer discipline from the foundations: primitives exist "so semantic tokens have somewhere
 * to point, and so a theme is a remapping rather than a rewrite", and layer 2 "is the only
 * colour layer components are allowed to consume". The CSS therefore emits primitives as
 * `--p-*` and semantics as `--color-*`, and the stylelint-style check below refuses a
 * component that reaches for a `--p-*`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (name) => fileURLToPath(new URL(name, import.meta.url));
const ds = JSON.parse(readFileSync(here("./ds.json"), "utf8"));

/**
 * Layer 1, both halves.
 *
 * `PRIMITIVES` is the light ramp exactly as the pinned source lists it. `DARK_RAMP` is the dark
 * one, which the source never collects into a ramp of its own -- it states each value inline in
 * the dark column of the semantic table, and `accent.light` in prose. Hoisting them here is
 * reading the source, not choosing values: every entry carries the row it was quoted from.
 *
 * They are one lookup because a theme is **a remapping of layer 2 onto layer 1**, so a dark
 * value has to resolve through a primitive for the same reason a light one does. Before this,
 * a dark value naming something outside `PRIMITIVES` resolved to nothing and the generator
 * skipped the declaration in silence -- see `buildCss`.
 */
const primitives = Object.fromEntries([
  ...ds.PRIMITIVES,
  ...(ds.DARK_RAMP ?? []).map(([name, hex]) => [name, hex]),
]);

/** Tokens whose dark value the source names and never defines. See `ds.json` DARK_GAPS. */
const darkGaps = new Map((ds.DARK_GAPS ?? []).map(([token, ref, why]) => [token, { ref, why }]));

/** `warm.700` -> `var(--p-warm-700)`; a literal (rgba, hex) passes through. */
function resolveRef(ref) {
  const value = String(ref).trim();
  // Dark-column entries often carry both a name and its hex: "dark.900 #1a1917".
  const hex = /#[0-9a-fA-F]{6}/.exec(value);
  if (/^rgba?\(/.test(value)) return value;
  const bare = value.split(/\s+/)[0];
  if (bare in primitives) {
    // "warm.0 + e1" is warm.0 with elevation, which is a shadow rather than a colour.
    // "ai.light at 1px" is a border width, likewise not part of the colour.
    return `var(--p-${bare.replace(/\./g, "-")})`;
  }
  if (hex) return hex[0].toLowerCase();
  return null;
}

function cssVarName(token) {
  return "--" + token.replace(/\./g, "-");
}

function buildCss() {
  const lines = [
    "/* GENERATED by src/design/generate.mjs from ds.json. Do not edit; run `npm run tokens`.",
    " *",
    " * Layer 1 primitives are --p-*. Components must not reference them: the foundations say",
    " * layer 2 is \"the only colour layer components are allowed to consume\", and a theme is a",
    " * remapping of layer 2 rather than a rewrite of layer 1.",
    " */",
    "",
    ":root {",
    "  /* Layer 1 - primitive ramps */",
  ];
  for (const [name, hex] of ds.PRIMITIVES) {
    lines.push(`  --p-${name.replace(/\./g, "-")}: ${hex};`);
  }
  lines.push("", "  /* Layer 1 - the dark ramp, quoted from the source's own dark column */");
  for (const [name, hex, source] of ds.DARK_RAMP ?? []) {
    lines.push(`  --p-${name.replace(/\./g, "-")}: ${hex}; /* ${source} */`);
  }
  lines.push("", "  /* Layer 2 - semantic tokens, light */");
  const unresolved = [];
  for (const [token, light, , use] of ds.SEMANTIC) {
    const value = resolveRef(light);
    if (!value) {
      unresolved.push(`${token} (light: ${light})`);
      continue;
    }
    lines.push(`  ${cssVarName(token)}: ${value}; /* ${use} */`);
  }
  lines.push("", "  /* Spacing. No value outside this scale ships. */");
  for (const [name, px] of SPACE) lines.push(`  --space-${name}: ${px}px;`);
  lines.push("", "  /* Radius: data stays sharp, anything pressable gets an affordance. */");
  lines.push("  --radius-card: 2px;");
  lines.push("  --radius-button: 6px;");
  lines.push("}", "");

  lines.push(
    "/* Dark is a remapping of the same token names -- never an inversion, and never a",
    " * second set of names. */",
    ':root[data-theme="dark"] {',
  );
  // **Every semantic token gets a dark declaration, or the build fails naming it.**
  //
  // The first version wrote `if (value) lines.push(...)` and said nothing when a dark value
  // did not resolve. Seven did not -- every one of them a name the source states somewhere
  // else, like `dark.950` or `accent.light` -- so those seven tokens simply kept their *light*
  // value in dark mode and the theme was partly not a theme. Three of the seven were visible:
  // form fields rendered near-white on a near-black page, the primary button stayed ink.600
  // against it, and `color.border.focus` -- the focus ring, which guardrail G4 makes
  // non-configurable precisely so "a tenant cannot ship an unnavigable product" -- was dark
  // navy on near-black. Nothing reported any of it. Found by looking at a dark render.
  //
  // This is the shape `CLAUDE.md` records for the backend over and over: a declared value that
  // nothing writes. The answer there is the same as here -- sweep the set rather than keep a
  // list, and make the absence fail.
  for (const [token, , dark] of ds.SEMANTIC) {
    const value = resolveRef(dark);
    if (value) {
      lines.push(`  ${cssVarName(token)}: ${value};`);
      continue;
    }
    const gap = darkGaps.get(token);
    if (gap && gap.ref === String(dark).trim()) {
      lines.push(`  /* ${cssVarName(token)}: no dark value -- ${dark}. See ds.json DARK_GAPS. */`);
      continue;
    }
    unresolved.push(`${token} (dark: ${dark})`);
  }
  lines.push("}", "");

  // **Inside its own `:root`.** The first version emitted these after the dark block and
  // outside any selector, so every `--type-*` declaration was inert -- a CSS variable
  // declared nowhere applies nowhere. The tokens test caught it by noticing the names
  // appeared only after `[data-theme="dark"]`.
  lines.push("/* The type scale, Latin. Arabic resolves through src/design/type.mjs. */");
  lines.push(":root {");
  for (const [name, size, weight, tracking] of ds.TYPE_SCALE) {
    const [px, lh] = size.split("/").map((s) => s.trim());
    const slug = name.replace(/\./g, "-");
    lines.push(`  --${slug}-size: ${px}px;`);
    lines.push(`  --${slug}-line: ${lh};`);
    lines.push(`  --${slug}-weight: ${weight};`);
    lines.push(`  --${slug}-tracking: ${tracking};`);
  }
  lines.push("}");
  return { css: lines.join("\n") + "\n", unresolved };
}

/** The spacing scale, read from the foundations' own annotations. */
const SPACE = [
  ["05", 2],
  ["1", 4],
  ["2", 8],
  ["3", 12],
  ["4", 16],
  ["5", 20],
  ["6", 24],
  ["8", 32],
  ["10", 40],
  ["12", 48],
  ["16", 64],
];

function buildModule() {
  const semantic = {};
  for (const [token, light, dark, use] of ds.SEMANTIC) {
    semantic[token] = { light, dark, use, css: `var(${cssVarName(token)})` };
  }
  return (
    "// GENERATED by src/design/generate.mjs from ds.json. Do not edit; run `npm run tokens`.\n" +
    "//\n" +
    "// `css` is what a component uses. The raw light/dark references are carried so a test\n" +
    "// can check a mapping against the design system without re-reading the HTML.\n\n" +
    `export const PRIMITIVES = ${JSON.stringify(primitives, null, 2)};\n\n` +
    `export const SEMANTIC = ${JSON.stringify(semantic, null, 2)};\n\n` +
    "// **An ordered array, not only a map.** A scale has an order, and a JavaScript object\n" +
    "// sorts integer-like keys numerically -- so `space.05` came last out of a map and the\n" +
    "// scale read as 4,8,...,64,2. The array is the scale; the map is a lookup.\n" +
    `export const SPACE_SCALE = ${JSON.stringify(SPACE)};\n\n` +
    `export const SPACE = ${JSON.stringify(Object.fromEntries(SPACE), null, 2)};\n\n` +
    "// Containers and data stay sharp; anything pressable gets 6px. `radius.button` is\n" +
    "// deliberately larger than `radius.card`, which looks wrong in a list and is right on\n" +
    "// screen -- the foundations say so in as many words.\n" +
    'export const RADIUS = { card: "2px", button: "6px" };\n'
  );
}

const outputs = [
  ["tokens.generated.css", buildCss().css],
  ["tokens.generated.mjs", buildModule()],
];

const check = process.argv.includes("--check");
let failed = false;
for (const [name, content] of outputs) {
  const path = here(`./${name}`);
  if (check) {
    let onDisk = null;
    try {
      onDisk = readFileSync(path, "utf8");
    } catch {
      console.error(`MISSING ${name}: run \`npm run tokens\``);
      failed = true;
      continue;
    }
    if (onDisk !== content) {
      console.error(`STALE ${name}: it does not match ds.json. Run \`npm run tokens\`.`);
      failed = true;
    } else {
      console.log(`ok ${name}`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${name} (${content.length} bytes)`);
  }
}

// **An unresolved token is a failure, not a note.**
//
// This used to print a sentence and exit 0, which is how seven tokens went without a dark
// value through a green `tokens:check`. A token the design system declares and this generator
// cannot emit is either a data error or a gap in the source -- the first has to be fixed and
// the second has to be *declared* in `DARK_GAPS` with a written reason, which is the only way
// a reader can tell "nobody noticed" from "the source does not say".
const { unresolved } = buildCss();
if (unresolved.length) {
  console.error(
    `\n${unresolved.length} semantic token(s) resolve to nothing. Fix the reference in ` +
      `ds.json, add the primitive it names, or declare it in DARK_GAPS with a reason:\n  ` +
      unresolved.join("\n  "),
  );
  failed = true;
}

for (const [token, ref, why] of ds.DARK_GAPS ?? []) {
  console.log(`gap  ${token} has no dark value (${ref}): ${why.split(".")[0]}.`);
}

process.exit(failed ? 1 : 0);
