import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";

import { fixture } from "./fixture-env";
import { signIn, useOwnerSession } from "./sign-in";

/**
 * ADM-TSK-01 · TASKS, ADM-CC-06 · ATTENTION ITEM DETAIL, ADM-CC-07 · RESOLVED TODAY.
 *
 * **Two readers, because three of these assertions need a session whose identity is a
 * person.** ADM-CC-06's five states include "assigned to me" and ADM-TSK-01's first chip is
 * "Mine", and both are derived from `ppl_identity_links` -- the owner holds every permission
 * in the catalogue and is nobody in this tenant, which is the ordinary state of a staff
 * login. So the fixture seeds a duty manager who *is* a person, and the owner then reads the
 * same item as somebody else's: both halves of the one state the canvas is most specific
 * about have a fixture rather than only a component test.
 *
 * **Nothing here presses a destructive control.** Resolving is one-way by trigger and
 * assigning writes a timeline entry nothing removes, so a spec that pressed either would pass
 * on the first run against a fresh fixture and fail on every run after it -- the trap this
 * suite has recorded three times. What is asserted is which controls are offered, which are
 * inert, and what each state says; the writes themselves are proven by
 * `backend/tests/test_tasks_api.py` and by the component tests over the decisions.
 */

const WCAG = ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"];
const creds = fixture();

test.describe("the task list", () => {
  test.beforeEach(async ({ page }) => {
    await useOwnerSession(page);
    await page.goto("/tasks");
  });

  test("names the source on every row, because a task nobody can account for is ignored",
    async ({ page }) => {
      const grid = page.locator("table").first();
      await expect(grid).toBeVisible();
      // **By cell, not by text.** `DataGrid` puts every droppable value in the DOM twice and
      // shows exactly one at any width, so a text locator inside a row resolves to the hidden
      // secondary fragment as well as the visible cell -- and `.first()` picks whichever the
      // markup emits first, which is the hidden one. That duplication is the component's own
      // documented mechanism and `phone.spec.ts` asserts it; a spec about content has to ask
      // for the cell.
      await expect(
        grid.getByRole("cell", { name: "Generated by an automation" }).first()).toBeVisible();
      await expect(
        grid.getByRole("cell", { name: "Assigned by a person" }).first()).toBeVisible();
    });

  test("counts the same work in the chips and in the table", async ({ page }) => {
    // **The defect this assertion exists for was on the screen.** The unfiltered list showed
    // every status while the chips counted work in hand, so the board read "Team · 7" over a
    // table of eight rows, one of them already done -- one screen with two definitions of
    // "open", found by rendering the page and reading it rather than by any assertion.
    const chip = page.getByRole("link", { name: /^Team · \d+$/ });
    const label = await chip.innerText();
    const counted = Number(label.replace(/\D/g, ""));
    await expect(page.locator("table tbody tr")).toHaveCount(counted);
    await expect(page.getByText(`${counted} tasks`)).toBeVisible();
  });

  test("shows no settled task, and says that is what the list is", async ({ page }) => {
    // The fixture settles one that is also five days past its due date, so a list showing
    // every status would carry it *and* the overdue filter would return it.
    await expect(page.getByText("Order the replacement turnstile board")).toHaveCount(0);
    // The sentence describing the list's own filter has gone -- the settled task is
    // absent, which is the assertion above, and the chips state the figures. GOV.UK's
    // test settles it: explaining how the interface works means something went wrong.
    await expect(page.locator("#main")).not.toContainText(/This list is work in hand/);
  });

  test("offers no checkbox on a blocked task, because it is unblocked first",
    async ({ page }) => {
      // `blocked -> done` is not an edge, in the Python table and in the trigger. A checkbox
      // the server would refuse is FD-06's "a button the module will refuse is worse than no
      // button", applied to the one in-hand status that cannot be settled.
      const blocked = page.locator("tbody tr").filter({ hasText: "Install the second turnstile" });
      await expect(blocked).toHaveCount(1);
      await expect(blocked.getByRole("checkbox")).toHaveCount(0);
      const open = page.locator("tbody tr").filter({ hasText: "Chase Omar" });
      await expect(open.getByRole("checkbox")).toHaveCount(1);
    });

  test("says why Mine counts nothing for an identity that is nobody", async ({ page }) => {
    // Not an empty queue: staff hold permissions and do not have to be anybody in particular,
    // so this is ordinary -- and a reader told nothing would conclude their tasks had gone.
    await expect(page.getByRole("link", { name: "Mine · 0" })).toBeVisible();
    await expect(page.getByText(/not linked to a person record/)).toBeVisible();
  });

  test("links a task born from an exception back to it", async ({ page }) => {
    // The canvas's own line, and the only navigation into ADM-CC-06 this build has.
    const row = page.locator("tbody tr").filter({ hasText: "Call Tareq Odeh" });
    await expect(row.getByText(`From exception ${creds.moneyCaseNumber}`)).toBeVisible();
    await row.getByRole("link", { name: /Call Tareq Odeh/ }).click();
    await expect(page.getByRole("heading", { level: 1 }))
      .toHaveText("6 payments failed overnight");
  });

  test("marks an overdue row and counts the overdue view separately", async ({ page }) => {
    const overdue = page.getByRole("link", { name: /^Overdue · \d+$/ });
    const counted = Number((await overdue.innerText()).replace(/\D/g, ""));
    await overdue.click();
    const rows = page.locator("tbody tr");
    // **The chip's figure and the view's rows, which is the invariant.** Both come from the
    // server over the same statuses and the same instant; a client filtering the page it was
    // given would report whichever rows happened to be loaded.
    await expect(rows).toHaveCount(counted);
    for (const text of await rows.allInnerTexts()) {
      // **Two forms, and both are right.** A task whose due instant has passed today is
      // overdue by no whole days -- "overdue 0 days" is not a sentence and English's plural
      // rules would pick it, so that case is its own message. This assertion is what caught
      // the label disagreeing with the filter: it used to demand a day count, and a task due
      // at nine this morning read "due today" at five in the afternoon while the chip counted
      // it as late.
      expect(text).toMatch(/overdue( \d+ days?)?\b/);
    }
  });

  test("has no accessibility violation", async ({ page }) => {
    const scan = await new AxeBuilder({ page }).withTags(WCAG).analyze();
    expect(scan.violations).toEqual([]);
  });
});

test.describe("the attention item", () => {
  test.beforeEach(async ({ page }) => {
    await useOwnerSession(page);
    await page.goto(`/tasks/cases/${creds.moneyCaseId}`);
  });

  test("carries the four facts the canvas prints under the headline", async ({ page }) => {
    for (const label of ["OWNER", "AGE", "AFFECTED", "SOURCE"]) {
      await expect(page.getByText(label, { exact: true })).toBeVisible();
    }
    await expect(page.getByText("Unassigned").first()).toBeVisible();
    // Six live records and a seventh withdrawn, which is the figure a batch action is sized
    // by -- a list that mixed the withdrawal in would inflate it.
    await expect(page.getByText("6 records")).toBeVisible();
  });

  test("lists the records it is about, and marks the one nothing can confirm",
    async ({ page }) => {
      const records = page.locator("section").filter({
        has: page.getByRole("heading", { name: "The records this is about" }),
      });
      // **The live list, not every `li` in the section.** The withdrawn record sits in the
      // same section and must: it is the same subject and the count a batch is sized by is
      // the live one, which is why the read returns them as two lists.
      await expect(records.locator("ul.ds-report-list > li")).toHaveCount(6);
      // A `lead` resolves against nothing in this build, and the read says which -- so an id
      // that looks verified is not presented as one.
      await expect(records.getByText(/Nothing in this build can confirm/)).toBeVisible();
    });

  test("keeps a withdrawn record rather than deleting it", async ({ page }) => {
    const gone = page.locator("section").filter({
      has: page.getByRole("heading", { name: "Taken off this item" }),
    });
    await expect(gone.getByText("his card went through on the retry")).toBeVisible();
  });

  test("puts the zone on every timeline row, because the gutter's clock is UTC",
    async ({ page }) => {
      // Ten sites in this app rendered a bare wall time with no zone, which was ambiguous
      // while every screen did it and misleading the day one started converting.
      await expect(page.getByText("Billing run · 6 of 214 charges declined")).toBeVisible();
      await expect(page.getByText(/\d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC · status_change/))
        .toBeVisible();
    });

  test("says what it cannot do rather than offering it", async ({ page }) => {
    // Each is a control the canvas draws and this build does not have, with the product's own
    // reason beside it -- a control absent with no reason reads as a permission the reader
    // lacks, and they go and ask for a grant that does not exist.
    await expect(page.locator("#main")).toContainText(/payment links/i);
    await expect(page.locator("#main")).not.toContainText(/30-second undo/);
    await expect(page.locator("#main")).not.toContainText(/offers Reopen on a resolved item/);
    await expect(page.getByRole("button", { name: "Reopen" })).toHaveCount(0);
  });

  test("offers the secondary route the canvas draws and this build has", async ({ page }) => {
    await expect(page.getByRole("link", { name: /recovery workspace/ }))
      .toHaveAttribute("href", "/payments/recovery");
  });

  test("reads an item somebody else holds as read-only, with a live take-over",
    async ({ page }) => {
      await page.goto(`/tasks/cases/${creds.assignedCaseId}`);
      await expect(page.getByText(/Somebody else is handling this/)).toBeVisible();
      // ADM-CC-06: "keeps every action visible but read-only ... and a Take over that records
      // the handover". So the actions are present and disabled, and the handover is not.
      await expect(page.getByRole("button", { name: "Snooze" })).toBeDisabled();
      await expect(page.getByRole("button", { name: "Resolve" })).toBeDisabled();
      await expect(page.getByRole("button", { name: "Take over" })).toBeVisible();
    });

  test("shows a deferral's reason and return date, and the way back", async ({ page }) => {
    await page.goto(`/tasks/cases/${creds.snoozedCaseId}`);
    await expect(page.getByText(/Deferred until/)).toBeVisible();
    // Twice on the page by design: once as the deferral's own reason beside the state, and
    // once inside the timeline entry the deferral wrote. Two renderings of one fact.
    await expect(page.getByText("the member is away until the ninth").first()).toBeVisible();
    // The remedy the routine deferral needs: a return date typed as next year would otherwise
    // hide an exception for eleven months with nothing able to undo it.
    await expect(page.getByRole("button", { name: "Return to the queue" })).toBeEnabled();
    await expect(page.getByRole("button", { name: "Snooze" })).toHaveCount(0);
  });

  test("has no accessibility violation", async ({ page }) => {
    const scan = await new AxeBuilder({ page }).withTags(WCAG).analyze();
    expect(scan.violations).toEqual([]);
  });
});

test.describe("the reader who is somebody", () => {
  // **Signs in rather than adopting the shared session**, because the only identity in this
  // fixture linked to a person is this one -- and the owner's saved state is the file every
  // other spec reads.
  test.beforeEach(async ({ page }) => {
    await signIn(page, { email: creds.taskEmail, password: creds.taskPassword });
  });

  test("counts their own work and reads their own item as theirs", async ({ page }) => {
    await page.goto("/tasks?view=mine");
    await expect(page.getByRole("link", { name: "Mine · 1" })).toBeVisible();
    await expect(page.getByText(/not linked to a person record/)).toHaveCount(0);
    await expect(page.locator("tbody tr")).toHaveCount(1);
    await expect(page.getByText("Confirm September class timetable")).toBeVisible();

    await page.goto(`/tasks/cases/${creds.assignedCaseId}`);
    await expect(page.getByText("Assigned to you").first()).toBeVisible();
    // Live, which is the half the owner's session can never prove.
    await expect(page.getByRole("button", { name: "Release" })).toBeEnabled();
    await expect(page.getByRole("button", { name: "Resolve" })).toBeEnabled();
    await expect(page.getByRole("button", { name: "Take over" })).toHaveCount(0);
  });
});

test.describe("resolved today", () => {
  test.beforeEach(async ({ page }) => {
    await useOwnerSession(page);
    await page.goto("/tasks/resolved");
  });

  test("states the count and the median, which the server computes", async ({ page }) => {
    // A median in a client is a second definition of a figure a manager quotes. The elapsed
    // times here are all under a minute, which is a property of the fixture rather than of
    // the screen -- `opened_at` is `now()` and no route backdates it -- so the *format* is
    // proven against the canvas's own `12m` / `1h 20m` / `2h 04m` in the component tests.
    // The count and the median are the two figures leading the board now, each with its
    // own label, rather than one 14px line.
    const figures = (await page.locator(".ds-metric-row").allInnerTexts()).join(" ")
      .toLowerCase();
    expect(figures).toContain("resolved today");
    expect(figures).toMatch(/median|nothing resolved/);
    await expect(page.locator("tbody tr")).toHaveCount(2);
  });

  test("is a record with no un-resolve anywhere on it", async ({ page }) => {
    // "Read-only for every role, including Owner" -- and this session holds every permission
    // in the catalogue, so its absence here is the canvas's rule rather than a refusal.
    // The sentence stating there is no un-resolve has gone; its own test asserts the
    // *absence* of any such control, which is the finding and is below.
    await expect(page.locator("#main")).not.toContainText(/There is no un-resolve/);
    // **Scoped to the page, not the document.** The chrome's language and theme switches are
    // buttons on every screen in this app, so a document-wide count asserts the shell rather
    // than the board -- and a spec that asserted four would then break the day the shell grew
    // a fifth control, for a reason that has nothing to do with this screen.
    await expect(page.locator("main").getByRole("button")).toHaveCount(0);
    // **The RESOLVER column has gone, and with it the note explaining its id.** A
    // resolver is an identity this read cannot name, so the only thing the cell could
    // hold was a uuid -- forty identical ones taking a quarter of the table. The absence
    // is named in the gap line; the sentence about it is not.
    await expect(page.locator("#main")).not.toContainText(/names the resolver/);
    await expect(page.locator("#main")).toContainText(/who resolved each one/);
  });

  test("links each row back to the item it resolved", async ({ page }) => {
    const row = page.locator("tbody tr").filter({ hasText: "Low stock" });
    await expect(row.getByRole("cell", { name: "Ordered" })).toBeVisible();
    await row.getByRole("link").first().click();
    await expect(page.getByRole("heading", { level: 1 }))
      .toHaveText("Low stock · protein bars, Khalda");
  });

  test("has no accessibility violation", async ({ page }) => {
    const scan = await new AxeBuilder({ page }).withTags(WCAG).analyze();
    expect(scan.violations).toEqual([]);
  });
});
